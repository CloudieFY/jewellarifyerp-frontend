export const uid = () =>
  Math.random().toString(36).slice(2, 8) + Date.now().toString(36).slice(-4);

// Returns the making charge on a PER-UNIT basis (i.e. before multiplying by qty),
// since calcItem multiplies the whole base (metal + making + stone + hmc) by qty.
// FIXED is divided by qty here so that, after that multiplication, it nets out to
// exactly `value` regardless of how many pieces are on the line.
export function computeMakingCharge(params: {
  type?: MakingChargeType;
  value: number;
  netWeight: number;
  ratePerGram: number;
  qty: number;
}) {
  const { type = "PERCENTAGE", value, netWeight, ratePerGram, qty } = params;
  switch (type) {
    case "PER_GRAM":
      return netWeight * value;
    case "PER_PIECE":
      return value;
    case "FIXED":
      return value / (qty || 1);
    case "WASTAGE":
      return (netWeight * (value / 100)) * ratePerGram;
    case "PERCENTAGE":
    default:
      return (netWeight * ratePerGram * value) / 100;
  }
}

export function calcItem(it: InvoiceItem, isGst: boolean) {
  const base = it.netWeight * it.ratePerGram + it.makingCharge + it.stoneCharge + (it.hmc || 0);
  const line = base * it.qty;
  const gst = isGst ? (line * it.gstPct) / 100 : 0;
  return { line, gst, total: line + gst };
}

export function inr(n: number) {
  return new Intl.NumberFormat("en-IN", {
    style: "currency",
    currency: "INR",
    maximumFractionDigits: 2,
  }).format(n || 0);
}


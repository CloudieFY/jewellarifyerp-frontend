export function getCleanInvoiceTitle(title?: string): string {
  if (!title || title.trim().toUpperCase() === "TAX INVOICE") {
    return "INVOICE";
  }
  return title;
}

export function getUpiQrCodeUrl(params: {
  upiId?: string;
  shopName?: string;
  phone?: string;
  qrCodeUrl?: string;
  amount?: number;
}): string {
  if (params.qrCodeUrl && params.qrCodeUrl.trim()) {
    return params.qrCodeUrl.trim();
  }
  const pa = params.upiId && params.upiId.trim() ? params.upiId.trim() : params.phone && params.phone.trim() ? `${params.phone.trim()}@ybl` : "";
  if (!pa) return "";
  const pn = encodeURIComponent(params.shopName || "Jewellery Shop");
  const am = params.amount && params.amount > 0 ? `&am=${params.amount}` : "";
  const upiUri = `upi://pay?pa=${pa}&pn=${pn}${am}&cu=INR`;
  return `https://api.qrserver.com/v1/create-qr-code/?size=250x250&margin=2&data=${encodeURIComponent(upiUri)}`;
}
